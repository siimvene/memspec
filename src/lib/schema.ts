import { z } from 'zod';
import {
  ALL_STATES,
  LIFECYCLE_STATES,
  MEMORY_KINDS,
  MEMORY_TYPES,
  QUESTION_STATES,
  SOURCE_KINDS,
  VERIFIED_WITH,
  DEFAULT_DECAY_DAYS,
  type MemoryFrontmatter,
} from './types.js';

const isoOrNever = z.string().refine(
  (s) => s === 'never' || !isNaN(Date.parse(s)),
  'Must be ISO 8601 date or "never"',
);

const codeAnchorSchema = z.object({
  file: z.string().describe('Path relative to the project root (POSIX separators).'),
  sha: z.string().describe('Git blob SHA of the file content at anchor time (as computed by `git hash-object`).'),
  repo: z.string().optional().describe('When set, `file` lives in another repo checked out next to this project (or under a configured search path).'),
});

const evidenceEntrySchema = z.object({
  sha256: z.string().optional().describe('sha256 (hex) of the copied file content; content-addresses the entry.'),
  name: z.string().optional().describe('Basename of the copied file as stored under `evidence/`.'),
  path: z.string().optional().describe('Path relative to the store root (under `evidence/`) where the file lives.'),
  source: z.string().optional().describe('Where the file was copied from: `~`-relative under the home directory, `repo:path` relative to a detected repo root, or omitted when neither applies. Never an absolute path.'),
  url: z.string().optional().describe('http(s) URL, recorded as a pointer without fetching (mutually exclusive with the file fields).'),
  captured_at: z.string().describe('ISO 8601 timestamp when the evidence was attached.'),
});

/**
 * v0.3 frontmatter schema. The reader normalizes legacy field/state names
 * (decay_after, corrects/corrected_by, correction_reason, captured/corrected/decayed/archived,
 * top-level confidence, ext.code_anchors) into this shape before validation.
 *
 * Field-level `.describe()` calls are the source of truth for `SCHEMA.md`
 * (generated by `scripts/generate-schema.ts`). Keep descriptions to one
 * sentence each; mirror wording from `types.ts` and `SPEC.md §6.2`.
 */
export const memoryFrontmatterSchema = z.object({
  id: z.string().regex(/^ms_[A-Z0-9]{26}$/, 'ID must be ms_ followed by a 26-char ULID')
    .describe('ULID prefixed with `ms_`; globally unique within the store and chronologically sortable.'),
  kind: z.enum(MEMORY_KINDS).default('claim')
    .describe('`claim` for fact/decision/procedure memories; `observation` for point-in-time notes that index a moment and expire rather than going stale.'),
  type: z.enum(MEMORY_TYPES).optional()
    .describe('Classification for claims (`fact` | `decision` | `procedure`); required when `kind: claim`, omitted on observations and questions.'),
  state: z.enum(ALL_STATES)
    .describe('Lifecycle state for claims/observations: `active` (current), `superseded` (replaced), or `retired` (no longer relevant). Questions instead use `open` (answer undecided) or `resolved` (settled).'),
  created: z.string().refine(
    (s) => !isNaN(Date.parse(s)),
    'Must be a valid ISO 8601 date',
  ).describe('ISO 8601 timestamp when this record was first written.'),
  source: z.string().min(1)
    .describe('Who wrote the record (agent name, human identifier, or import label); required at write time, `"unknown"` is rejected.'),
  source_kind: z.enum(SOURCE_KINDS).optional()
    .describe('Trust tier inferred from `source` at write time: `operator` (human), `agent`, or `import`.'),
  tags: z.array(z.string()).default([])
    .describe('Free-form tag list for filtering and search.'),
  scope: z.string().min(1).optional()
    .describe('Read-side partition matching a `scopes:` key in config.yaml. Absent means visible from every scope (the default for pre-scoping records); `universal` means explicitly visible everywhere; any other value restricts the record to that one active scope.'),
  check_by: isoOrNever
    .describe('ISO 8601 deadline or `"never"`; when it passes the record is flagged `stale: true` at read time but never deleted (renamed from `decay_after`; a legacy `decay_after: never` on a claim reads as the type default TTL, only an explicit `check_by: never` pins).'),
  stale: z.boolean().optional()
    .describe('Set when `check_by` has passed; cleared by a successful `verify`. Lazy-flagged in memory on read; physical removal only via `memspec sweep`.'),
  last_verified: z.string().refine(
    (s) => !isNaN(Date.parse(s)),
    'Must be a valid ISO 8601 date',
  ).optional().describe('ISO 8601 timestamp of the last successful verification; defaults to `created` when never verified.'),
  verified_with: z.enum(VERIFIED_WITH).optional()
    .describe('Witness class for the last verification, in descending strength: `anchor` > `probe` > `operator` > `evidence` > `assertion`. Replaces the retired `confidence` field. `probe` is written only by `memspec probe` itself (`--set` or a matching re-check) — the entry point that actually executed the command; `verify` never runs probes.'),
  pinned: z.boolean().optional()
    .describe('Operator-only flag; pinned claims are always surfaced in boot context (cap 5, ordered by `last_verified` descending).'),
  anchors: z.array(codeAnchorSchema).optional()
    .describe('Code anchors linking this memory to specific file contents; drift detected by comparing recorded SHA to current `git hash-object`. Promoted from `ext.code_anchors` to schema spine in v0.3.'),
  probe: z.object({
    cmd: z.string().describe('Shell command executed from the project root when the probe is re-run.'),
    hash: z.string().describe('sha256 (hex) of the command stdout at baseline time.'),
  }).optional()
    .describe('A shell command plus the sha256 of its baseline stdout; a re-run whose output hashes differently marks the record drifted. Executes only via explicit `memspec probe`, gated by the machine-local trustfile (`.probe-trust.json`) — never on a read path and never inside `verify`, because record content is untrusted and the command shells out.'),
  supersedes: z.array(z.string()).optional()
    .describe('Ids this record replaces (renamed from `corrects`; now an array to support N→1 merges).'),
  superseded_by: z.string().optional()
    .describe('Id of the record that replaced this one (renamed from `corrected_by`).'),
  supersede_reason: z.string().optional()
    .describe('Durable reason explaining why this record was superseded (renamed from `correction_reason`).'),
  conflicts_with: z.array(z.string()).optional()
    .describe('Explicit conflict links to other memory ids; surfaced on read so contradictions are visible rather than blindly ranked.'),
  refines: z.array(z.string()).optional()
    .describe('Ids of notes this record refines or elaborates on; the parent stays valid (v0.4 named link).'),
  supports: z.array(z.string()).optional()
    .describe('Ids of notes this record provides evidence for (v0.4 named link).'),
  depends_on: z.array(z.string()).optional()
    .describe('Ids of notes this record presupposes — a knowledge or chronological dependency (v0.4 named link).'),
  derived_from: z.array(z.string()).optional()
    .describe('Ids of records this record was INFERRED from rather than observed directly; a record carrying any is `derived` (v0.11 named link).'),
  distinct_from: z.array(z.string()).optional()
    .describe('Ids of records the writer compared with this one and judged independent: neither contradicts, refines, supports nor depends on the other. Acknowledges an overlap for `memspec check`; not a retrieval edge, never followed by search expansion or lineage (v0.13).'),
  requires_human: z.array(z.string()).optional()
    .describe('Procedures only: step labels or short phrases a human must perform; an unattended runner refuses these steps. Schema error on non-procedure records (v0.11 actuation boundary).'),
  evidence: z.array(evidenceEntrySchema).optional()
    .describe('Committed evidence attachments (v0.11 Layer B): content-addressed local file copies under `evidence/`, or http(s) URL pointers recorded without fetching. A file-backed entry witnesses an anchorless claim as `evidence`.'),
  answers: z.array(z.string()).optional()
    .describe('Questions only: competing answer record ids for this question (v0.11 question groups).'),
  closed: z.boolean().optional()
    .describe('Questions only: `true` means the listed `answers` are the only candidates (closed-world), enabling resolution by elimination (v0.11 question groups).'),
  resolved_by: z.string().optional()
    .describe('Questions only: the surviving answer id, set when the question `state` is `resolved` (v0.11 question groups).'),
  expires: z.string().refine(
    (s) => !isNaN(Date.parse(s)),
    'Must be a valid ISO 8601 date',
  ).optional().describe('Observations only: hard ISO 8601 expiry after which the record is no longer surfaced.'),
  valid_from: z.iso.datetime().optional()
    .describe('ISO 8601 timestamp when the world-state truth claimed by this record becomes valid. Open-ended if absent. Orthogonal to `check_by` — validity bounds the truth window; `check_by` bounds the review schedule.'),
  valid_to: z.iso.datetime().optional()
    .describe('ISO 8601 timestamp when the world-state truth ceases to hold. Open-ended if absent. Orthogonal to `check_by` — past `valid_to` means the fact is no longer true, past `check_by` only means review is overdue.'),
  ext: z.record(z.string(), z.unknown()).optional()
    .describe('Extension bag for non-schema fields (e.g. `ext.confirmations`, `ext.last_verification`, `ext.legacy_confidence`). Conventions documented in `src/lib/types.ts`.'),
}).refine(
  (data) => data.kind === 'observation' || data.kind === 'question' || data.type !== undefined,
  { message: 'Claims (kind: claim) require a type', path: ['type'] },
).refine(
  (data) => data.kind !== 'question' || data.type === undefined,
  { message: 'Questions (kind: question) do not carry a type', path: ['type'] },
).refine(
  (data) => data.kind === 'question'
    ? (QUESTION_STATES as readonly string[]).includes(data.state)
    : (LIFECYCLE_STATES as readonly string[]).includes(data.state),
  { message: 'state must be open|resolved for questions, active|superseded|retired otherwise', path: ['state'] },
).refine(
  (data) => data.requires_human === undefined || data.type === 'procedure',
  { message: 'requires_human is only allowed on type: procedure records', path: ['requires_human'] },
).refine(
  (data) => data.kind === 'question' || (data.answers === undefined && data.closed === undefined && data.resolved_by === undefined),
  { message: 'answers/closed/resolved_by are only allowed on kind: question records', path: ['answers'] },
);

export type MemoryItemFrontmatter = z.infer<typeof memoryFrontmatterSchema>;

const LEGACY_STATE_MAP: Record<string, string> = {
  captured: 'active',
  corrected: 'superseded',
  decayed: 'retired',
  archived: 'retired',
};

/**
 * Map a legacy frontmatter object into v0.3 shape so the same validator
 * accepts pre-0.3 records. Mutates a clone, never the input.
 *
 * - state: captured → active, corrected → superseded, decayed|archived → retired
 * - decay_after → check_by, except legacy `decay_after: never` on a claim (see
 *   `legacyNeverCheckBy`)
 * - corrects (string) → supersedes (array)
 * - corrected_by → superseded_by
 * - correction_reason → supersede_reason
 * - ext.code_anchors → top-level anchors (if anchors not already set)
 * - top-level confidence → ext.legacy_confidence (and removed from top level)
 */
/**
 * The `check_by` a legacy `decay_after: never` claim reads as: the type's TTL
 * counted from `last_verified`, else `created`. The TTL is the store's
 * `config.yaml` `decay:` value for that type when the caller has the store
 * config (`decayDays`, from `decayDaysByType`), else `DEFAULT_DECAY_DAYS`.
 *
 * Pre-0.3 writers stamped `decay_after: never` as a default on whole batches
 * of records (imports, early agent writes), so the value records no decision.
 * Mapping it straight to `check_by: never` exempted those records from every
 * staleness check forever: a team decision imported in Sept 2026 kept ranking
 * `stale: false` months after the auth flow and vendor price it cited had
 * changed, and a stale-record cleanup never saw it. An explicit v0.3
 * `check_by: never` is different: it is written deliberately (`verify
 * --check-by never`, settled event records) and stays honoured, which is why
 * this only runs when `check_by` is absent.
 *
 * Computed at read time, so nothing is rewritten on disk; `memspec migrate`
 * persists the same value. Returns undefined for non-claims (observations
 * expire on their own clock, questions never go stale) and when the base date
 * does not parse, leaving the caller's old mapping in place.
 */
export function legacyNeverCheckBy(
  data: Record<string, unknown>,
  decayDays: Partial<Record<string, number>> = DEFAULT_DECAY_DAYS,
): string | undefined {
  if (data.kind !== undefined && data.kind !== 'claim') return undefined;
  const asIso = (v: unknown): unknown => (v instanceof Date ? v.toISOString() : v);
  const base = asIso(data.last_verified) ?? asIso(data.created);
  if (typeof base !== 'string') return undefined;
  const baseMs = Date.parse(base);
  if (Number.isNaN(baseMs)) return undefined;
  const type = typeof data.type === 'string' ? data.type : undefined;
  const days = (type ? decayDays[type] ?? DEFAULT_DECAY_DAYS[type as keyof typeof DEFAULT_DECAY_DAYS] : undefined) ?? 90;
  return new Date(baseMs + days * 24 * 60 * 60 * 1000).toISOString();
}

/** Store context for normalisation; absent fields fall back to the built-in defaults. */
export interface NormalizeOptions {
  /** Per-type TTL in days from the store's `config.yaml` `decay:` block (`decayDaysByType`). */
  decayDays?: Partial<Record<string, number>>;
}

export function normalizeLegacyFrontmatter(input: Record<string, unknown>, options: NormalizeOptions = {}): Record<string, unknown> {
  const data = { ...input };

  if (data.kind === undefined) data.kind = 'claim';

  if (typeof data.state === 'string' && data.state in LEGACY_STATE_MAP) {
    data.state = LEGACY_STATE_MAP[data.state];
  }

  if (data.check_by === undefined && data.decay_after !== undefined) {
    data.check_by = data.decay_after === 'never'
      ? legacyNeverCheckBy(data, options.decayDays) ?? data.decay_after
      : data.decay_after;
  }
  delete data.decay_after;

  if (data.supersedes === undefined && data.corrects !== undefined) {
    const raw = data.corrects;
    data.supersedes = Array.isArray(raw) ? raw : [raw];
  }
  delete data.corrects;

  if (data.superseded_by === undefined && data.corrected_by !== undefined) {
    data.superseded_by = data.corrected_by;
  }
  delete data.corrected_by;

  if (data.supersede_reason === undefined && data.correction_reason !== undefined) {
    data.supersede_reason = data.correction_reason;
  }
  delete data.correction_reason;

  const ext = (data.ext && typeof data.ext === 'object') ? { ...(data.ext as Record<string, unknown>) } : undefined;

  // Anchor promotion: ext.code_anchors → top-level anchors (if not already top-level).
  if (data.anchors === undefined && ext && Array.isArray(ext.code_anchors)) {
    data.anchors = ext.code_anchors;
  }

  // Confidence retirement: keep the historical value as ext.legacy_confidence; drop top-level.
  if (typeof data.confidence === 'number') {
    if (ext) {
      if (ext.legacy_confidence === undefined) ext.legacy_confidence = data.confidence;
    } else {
      data.ext = { legacy_confidence: data.confidence };
    }
  }
  delete data.confidence;

  if (ext !== undefined) data.ext = ext;

  return data;
}

export function validateFrontmatter(
  data: unknown,
  options: NormalizeOptions = {},
): { success: true; data: MemoryItemFrontmatter } | { success: false; errors: string[] } {
  const normalized = data && typeof data === 'object'
    ? normalizeLegacyFrontmatter(data as Record<string, unknown>, options)
    : data;
  const result = memoryFrontmatterSchema.safeParse(normalized);
  if (result.success) {
    return { success: true, data: result.data };
  }
  return {
    success: false,
    errors: result.error.issues.map((i) => `${i.path.join('.')}: ${i.message}`),
  };
}

export function assertValidFrontmatter(data: unknown, options: NormalizeOptions = {}): MemoryFrontmatter {
  const normalized = data && typeof data === 'object'
    ? normalizeLegacyFrontmatter(data as Record<string, unknown>, options)
    : data;
  return memoryFrontmatterSchema.parse(normalized) as MemoryFrontmatter;
}
